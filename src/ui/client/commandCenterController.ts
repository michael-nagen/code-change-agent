/**
 * Client app: the Project Command Center controller.
 *
 * Makes a project feel "already connected" so the everyday flow is
 * select-project → click an action, not paste-everything-again. It owns:
 *   - a small browser-local (localStorage) store of per-project context
 *     (spec/diff/GitHub URL) plus a summary of the last run — this is the
 *     smallest safe way to reuse inputs without any backend/persistence change;
 *   - a clearly-labeled sample project so mock/demo mode starts pre-connected;
 *   - the connected-context panel, the "context this run will use" pills, and
 *     the one-click action buttons;
 *   - launching a run via the workspace's shared `submitRun`, passing saved
 *     context instead of reading the manual form.
 *
 * It never calls the network directly (it goes through `submitRun` → `api`) and
 * holds no artifact-rendering logic (that stays in the workspace controller).
 * Emitted as source lines because the whole client is one inline script.
 */
