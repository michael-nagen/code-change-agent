  "function ccActive() {",
  "  var store = ccRead();",
  "  if (store.activeProject && store.projects[store.activeProject]) return store.projects[store.activeProject];",
  "  for (var k in store.projects) { if (store.projects.hasOwnProperty(k)) return store.projects[k]; }",
  "  // Demo default: a clearly-labeled pre-connected project, mock mode only.",
  "  if (ccMode() === 'mock') return CC_SAMPLE;",
  "  return null;",
  "}",
