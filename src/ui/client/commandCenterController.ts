  "  var ctx = ccFormCtx();",
  "  if (ctx.projectName) ccUpsert(ctx);",
  "  var name = ctx.projectName || (data.memory && data.memory.projectName) || '';",
  "  ccSetLastRun(name, ccRunInfo(data));",
  "  renderCommandCenter();",
  "}",
