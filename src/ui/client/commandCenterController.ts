  "",
  "function ccOpenAdvanced() { var d = $('advanced-input'); if (d) { d.open = true; if (d.scrollIntoView) d.scrollIntoView({ behavior: 'smooth', block: 'start' }); } var r = $('requirementText'); if (r && r.offsetParent !== null) r.focus(); }",
  "function ccSaveContext() {",
  "  var ctx = ccFormCtx();",
  "  if (!ctx.projectName) { setStatus('error', 'Add a project name in Advanced / Manual Input first.'); ccOpenAdvanced(); return; }",
  "  var hasSpec = (ctx.requirementText && ctx.requirementText.trim() !== '') || (ctx.inputMode === 'githubUrl' && ctx.githubUrl && ctx.githubUrl.trim() !== '');",
  "  if (!hasSpec) { setStatus('error', 'Add a requirement / spec (or a GitHub URL) before saving.'); ccOpenAdvanced(); return; }",
