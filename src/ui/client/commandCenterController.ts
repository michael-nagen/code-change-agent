  "function ccRead() {",
  "  try {",
  "    var raw = window.localStorage.getItem(CC_STORE_KEY);",
  "    if (!raw) return { projects: {}, activeProject: null };",
  "    var v = JSON.parse(raw);",
  "    if (!v || typeof v !== 'object') return { projects: {}, activeProject: null };",
